"""Write src/fxout_coef.inc: the FX OUT page's Low Cut as 12 dB/oct high-pass biquads (RBJ cookbook, Q = 0.7071),
one row per list entry, for the delay slot (48 kHz) and the reverb's core (29.8 kHz). python3 host/gen_fxout_coef.py"""
import math
import os

CUTS = [30, 60, 100, 150, 200, 300, 400, 600]          # Hz; list entry k + 1 (entry 0 = Off)
RATES = [("48 kHz: the delay slot", 48000.0), ("29.8 kHz: the reverb core", 29800.0)]


def hp(f, fs, q=1 / math.sqrt(2)):
    w = 2 * math.pi * f / fs
    c, a = math.cos(w), math.sin(w) / (2 * q)
    a0 = 1 + a
    return [(1 + c) / 2 / a0, -(1 + c) / a0, (1 + c) / 2 / a0, -2 * c / a0, (1 - a) / a0]


out = ["/* generated by host/gen_fxout_coef.py - do not edit. {b0, b1, b2, a1, a2}, y = b0 x + b1 x1 + b2 x2 - a1 y1 - a2 y2 */",
       f"#define FXOUT_CUTS {len(CUTS)}",
       "static const char *const fxout_cut_names[FXOUT_CUTS + 1] = {\"Off\", " + ", ".join(f'"{f} Hz"' for f in CUTS) + "};",
       "static const float fxout_coef[2][FXOUT_CUTS][5] = {"]
for name, fs in RATES:
    out.append(f"    {{   /* {name} */")
    for f in CUTS:
        out.append("        {" + ", ".join(f"{v:.9g}f" for v in hp(f, fs)) + f"}},   /* {f} Hz */")
    out.append("    },")
out.append("};")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "fxout_coef.inc"), "w").write("\n".join(out) + "\n")
print("src/fxout_coef.inc:", len(CUTS), "cut-offs x", len(RATES), "rates")
