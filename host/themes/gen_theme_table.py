"""Write src/theme_palettes.inc from make_themes.py's THEMES: python3 host/themes/gen_theme_table.py.
The firmware's Theme list is SHIPPED below (order = the list on TOOLS); "Stock" is first and always present. Entry 0
stays transparent black (stock's own entry 0 is 0x00000000), every other entry is opaque ARGB8888."""
import contextlib
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
with contextlib.redirect_stdout(io.StringIO()):
    import make_themes as m

SHIPPED = [("Stock", "Stock 3.1.9"), ("Midnight", "Midnight"), ("Blue LCD", "Blue LCD"), ("Amber VFD", "Amber VFD")]
by_name = {n: p for n, _, p in m.THEMES if p is not None}


def lum(c):
    ch = [int(c[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    ch = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]


def contrast(a, b):
    lo, hi = sorted((lum(a), lum(b)))
    return (hi + 0.05) / (lo + 0.05)


# Contrast floors, from the glass (3.3.n2 photos, 10-19). Fills under the text (select 4 / 32, accent 5 / 10: the
# selected pad / Tools row, the lit VEL button and selected tab) >= 2.3, Amber VFD's orange select, the lowest one
# that read fine; mint / yellow / light cyan at 1.0-1.4 did not. Greys 9 + 17 (the waveform labels) vs the
# background >= 3.5; stock's #707070 on #141414 is 3.7, every theme's 1.3-1.5 was invisible.
bad = []
for short, name in SHIPPED[1:]:
    p = by_name[name]
    for i in (4, 32, 5, 10):
        if contrast(p[i], p[15]) < 2.3:
            bad.append(f"{short}: colour {i} {p[i]} under text {p[15]} = {contrast(p[i], p[15]):.2f} (< 2.3)")
    for i in (9, 17):
        if contrast(p[i], p[2]) < 3.5:
            bad.append(f"{short}: colour {i} {p[i]} on background {p[2]} = {contrast(p[i], p[2]):.2f} (< 3.5)")
if bad:
    sys.exit("contrast too low:\n  " + "\n  ".join(bad))
out = ["/* generated by host/themes/gen_theme_table.py from make_themes.py - do not edit */",
       f"#define THEMES {len(SHIPPED)}",
       "static const char *const theme_names[THEMES] = {" + ", ".join(f'"{s}"' for s, _ in SHIPPED) + "};",
       "static const uint32_t theme_palettes[THEMES - 1][34] = {      /* Stock is read from flash, not stored */"]
for short, name in SHIPPED[1:]:
    words = [0] + [0xFF000000 | int(c[1:], 16) for c in by_name[name][1:]]
    out.append(f"    /* {short} */")
    for i in range(0, 34, 6):
        out.append("    " + ("{" if i == 0 else " ") + ", ".join(f"0x{w:08x}u" for w in words[i:i + 6]) + ("}," if i + 6 >= 34 else ","))
out.append("};")
open(os.path.join(HERE, "..", "..", "src", "theme_palettes.inc"), "w").write("\n".join(out) + "\n")
print("src/theme_palettes.inc:", len(SHIPPED), "themes")
