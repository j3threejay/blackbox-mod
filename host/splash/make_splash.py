"""The boot splash image for the firmware: python3 host/splash/make_splash.py -> src/splash_img.c (+ splash-B-screen.png).

The pick (2026-10-17) is mock-up B (splash-B.svg, make_mock.py): the faceplate logo, "JOEBOX 1" in dot-matrix,
"BLACKBOX MOD / BY JUSTIN JOE", on black. The mock-up's small "JOEBOX 1" bottom right only stood in for the firmware's
own version label, which a test build still draws there (src/splash.c), so it is taken out here.
Steps: render the SVG at exactly 320 x 240 (headless Chrome, as the mock-ups were checked), cut to the screen's 15-bit
colour (ARGB1555), quantize to 222 colours (CLUT entries 34..255: 0..33 are the GUI's palette), run-length encode
the indices top row first (pairs: count 1..255, index), and write them as bank 2 data.
"""
import os
import re
import subprocess
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
W, H, FIRST, COLOURS = 320, 240, 34, 222

svg = open(os.path.join(HERE, "splash-B.svg")).read()
svg, n = re.subn(r'<text x="312" y="234"[^>]*>JOEBOX 1</text>', "", svg)
assert n == 1, "the stand-in version label was not found in splash-B.svg"
with tempfile.TemporaryDirectory() as tmp:
    src, png = os.path.join(tmp, "s.svg"), os.path.join(tmp, "s.png")
    open(src, "w").write(svg)
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", f"--window-size={W},{H}",
                    "--force-device-scale-factor=1", f"--screenshot={png}", "file://" + src],
                   check=True, capture_output=True)
    img = Image.open(png).convert("RGB")
assert img.size == (W, H), img.size

px = img.load()                                          # the screen's 15-bit colour, as the mock-ups showed it
for y in range(H):
    for x in range(W):
        r, g, b = px[x, y]
        px[x, y] = tuple((v >> 3) * 255 // 31 for v in (r, g, b))
q = img.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = q.getpalette()[:3 * COLOURS]
idx = list(q.getdata())
used = max(idx) + 1

err = 0
rgb = list(img.getdata())
for i, p in zip(idx, rgb):
    err = max(err, max(abs(pal[3 * i + k] - p[k]) for k in range(3)))

rle, i = [], 0
while i < len(idx):
    j = i
    while j < len(idx) and idx[j] == idx[i] and j - i < 255:
        j += 1
    rle += [j - i, FIRST + idx[i]]
    i = j

q.convert("RGB").resize((W * 3, H * 3), Image.NEAREST).save(os.path.join(HERE, "splash-B-screen.png"))
words = [0xFF000000 | pal[3 * k] << 16 | pal[3 * k + 1] << 8 | pal[3 * k + 2] for k in range(used)]
out = ["/* generated by host/splash/make_splash.py from splash-B.svg - do not edit. Bank 2 data (build.sh BANK2_SRCS). */",
       "#include <stdint.h>",
       f"/* {W} x {H}, {used} colours = CLUT entries {FIRST}..{FIRST + used - 1}, ARGB8888, all opaque; worst channel "
       f"error after quantizing {err} of 255 */",
       f"const uint32_t splash_colours = {used};",
       f"const uint32_t splash_clut[{used}] = {{"]
for k in range(0, used, 8):
    out.append("    " + ", ".join(f"0x{w:08x}u" for w in words[k:k + 8]) + ",")
out += ["};", f"/* run-length pairs (count 1..255, CLUT index), the top row first: {len(rle)} bytes for {W * H} pixels */",
        f"const uint32_t splash_rle_len = {len(rle)};", f"const uint8_t splash_rle[{len(rle)}] = {{"]
for k in range(0, len(rle), 24):
    out.append("    " + ", ".join(str(v) for v in rle[k:k + 24]) + ",")
out.append("};")
open(os.path.join(ROOT, "src", "splash_img.c"), "w").write("\n".join(out) + "\n")
print(f"src/splash_img.c: {used} colours, worst error {err}/255, {len(rle)} bytes RLE ({W * H} pixels); "
      f"preview host/splash/splash-B-screen.png")
